extension Theme {
    enum CornerRadius {
        /// Default small corner radius of 8.
        static let small: CGFloat = 8
        /// Default medium corner radius of 12.
        static let medium: CGFloat = 12
        /// Default large corner radius of 16.
        static let large: CGFloat = 16
    }
}
